const dicts: Record<Lang, Dict> = { fa, en };

// --- current language: a tiny external store, so React re-renders on change ---

let lang: Lang = 'fa';
const listeners = new Set<() => void>();

export function getLang(): Lang {
  return lang;
}

export function setLang(next: Lang): void {
  lang = next === 'en' ? 'en' : 'fa';
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'fa' ? 'rtl' : 'ltr';
  try { localStorage.setItem('dx-lang', lang); } catch { /* storage may be blocked */ }
  listeners.forEach(fn => fn());
}

export function subscribeLang(fn: () => void): () => void {
  listeners.add(fn);
  return () => { listeners.delete(fn); };
}

/** The language saved by the boot script (see app/layout.tsx). */
export function initLang(): void {
  lang = document.documentElement.lang === 'en' ? 'en' : 'fa';
}

export function t(key: string, vars?: Record<string, string | number>): string {
  let s = dicts[lang][key] ?? dicts.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

/** true when the key exists (used for optional translations). */
export function hasKey(key: string): boolean {
  return key in dicts[lang] || key in dicts.en;
}

export function fmtNumber(n: number | null | undefined): string {
  if (n == null || Number.isNaN(n)) return '—';
  return new Intl.NumberFormat(lang === 'fa' ? 'fa-IR' : 'en-US').format(n);
}

export function fmtDate(iso: string | null | undefined): string {
  if (!iso) return '—';
  const d = new Date(iso);
  return new Intl.DateTimeFormat(lang === 'fa' ? 'fa-IR' : 'en-US', { dateStyle: 'medium', timeStyle: 'short' }).format(d);
}

export function fmtTime(iso: string | null | undefined): string {
  if (!iso) return '';
  return new Date(iso).toLocaleTimeString('en-GB', { hour12: false });
}
